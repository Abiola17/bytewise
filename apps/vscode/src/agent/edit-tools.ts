const editArgs = z.object({
  path: z.string().min(1).max(1024),
  edits: z
    .array(z.object({ find: z.string().max(50_000), replace: z.string().max(50_000) }))
    .min(1),
  explanation: z.string().max(2000).default(""),
});
const createArgs = z.object({
  path: z.string().min(1).max(1024),
  content: z.string().max(500_000),
  explanation: z.string().max(2000).default(""),
});

const refuse = (summary: string, output: string): ToolOutcome => ({ ok: false, summary, output });

/** Writable paths: inside the workspace, allowed by the policy, not generated, not through links. */
async function checkWritable(
  fs: WorkspaceFs,
  input: string,
): Promise<{ path: string } | { error: string }> {
  const target = normalizeToolPath(input);
  if ("error" in target) return target;
  if (!target.path) return { error: "A file path is required." };
  const policy = checkRelativePath(target.path);
  if (!policy.allowed) return { error: policy.reason };
  if (isGeneratedFile(target.path)) {
    return {
      error: "Lockfiles are generated by the package manager and must not be edited by hand.",
    };
  }
  return target;
}

/** For new files: every existing folder on the way must be a real directory (not a link or a file). */
async function parentsAreSafe(fs: WorkspaceFs, rel: string): Promise<boolean> {
  const parts = rel.split("/");
  for (let i = 1; i < parts.length; i++) {
    const stat = await fs.stat(parts.slice(0, i).join("/"));
    if (!stat) return true; // the rest will be created
    if (stat.kind !== "directory") return false;
  }
  return true;
}

function outcomeFor(proposal: EditProposal, decision: EditDecision): ToolOutcome {
  const what = proposal.kind === "create" ? "new file" : "edit to";
  const stats = `+${proposal.additions} −${proposal.deletions}`;
  switch (decision.decision) {
    case "accepted":
      return {
        ok: true,
        summary: `Applied ${what} ${proposal.path} (${stats})`,
        output: `The developer accepted the change. ${proposal.path} has been updated and saved.`,
        path: proposal.path,
      };
    case "rejected":
      return {
        ok: false,
        summary: `Rejected ${what} ${proposal.path}`,
        output: `The developer rejected this change; ${proposal.path} is unchanged.${decision.note ? ` Their note: ${decision.note}` : ""} Do not propose the same change again unless they ask; ask what they would prefer instead.`,
        path: proposal.path,
      };
    case "failed":
      return {
        ok: false,
        summary: `Could not apply ${what} ${proposal.path}`,
        output: `The change was not applied: ${decision.reason} Read the file again before proposing a new edit.`,
        path: proposal.path,
      };
  }
}

/** Runs edit_file / create_file. Never throws; nothing is written without approval. */
export async function runEditTool(options: {
  fs: WorkspaceFs;
  host: EditHost;
  name: string;
  rawArguments: string;
  newId: () => string;
}): Promise<ToolOutcome> {
  const { fs, host, name, newId } = options;
  let raw: unknown;
  try {
    raw = JSON.parse(options.rawArguments || "{}");
  } catch {
    return refuse(`${name} (invalid arguments)`, "The tool arguments were not valid JSON.");
  }

  if (name === "edit_file") {
    const args = editArgs.safeParse(raw);
    if (!args.success)
      return refuse(
        "Edit (invalid arguments)",
        'edit_file needs "path", "edits" [{find, replace}] and "explanation".',
      );
    const target = await checkWritable(fs, args.data.path);
    if ("error" in target) return refuse(`Edit refused: ${args.data.path}`, target.error);
    const stat = await fs.stat(target.path);
    if (!stat)
      return refuse(
        `Edit failed: ${target.path}`,
        `"${target.path}" does not exist. Use create_file for new files.`,
      );
    if (stat.kind !== "file" || !(await hasRealParents(fs, target.path))) {
      return refuse(
        `Edit refused: ${target.path}`,
        `"${target.path}" is not a regular file in the workspace.`,
      );
    }
    const before = await fs.readText(target.path);
    const result = computeEdit(before, args.data.edits);
    if (!result.ok) {
      return refuse(`Edit could not be prepared: ${target.path}`, result.problems.join("\n"));
    }
    const proposal: EditProposal = {
      id: newId(),
      kind: "edit",
      path: target.path,
      before,
      after: result.content,
      explanation: args.data.explanation,
      ...lineStats(before, result.content),
      warning: editWarning(target.path),
    };
    return outcomeFor(proposal, await host.requestApproval(proposal));
  }

  if (name === "create_file") {
    const args = createArgs.safeParse(raw);
    if (!args.success)
      return refuse(
        "Create (invalid arguments)",
        'create_file needs "path", "content" and "explanation".',
      );
    const target = await checkWritable(fs, args.data.path);
    if ("error" in target) return refuse(`Create refused: ${args.data.path}`, target.error);
    if (await fs.stat(target.path)) {
      return refuse(
        `Create refused: ${target.path}`,
        `"${target.path}" already exists. Use edit_file to change it.`,
      );
    }
    if (!(await parentsAreSafe(fs, target.path))) {
      return refuse(`Create refused: ${target.path}`, "A folder on that path is a file or a link.");
    }
    const proposal: EditProposal = {
      id: newId(),
      kind: "create",
      path: target.path,
      before: "",
      after: args.data.content,
      explanation: args.data.explanation,
      ...lineStats("", args.data.content),
      warning: editWarning(target.path),
    };
    return outcomeFor(proposal, await host.requestApproval(proposal));
  }

  return refuse(`Unknown tool ${name}`, `There is no tool named "${name}".`);
}
